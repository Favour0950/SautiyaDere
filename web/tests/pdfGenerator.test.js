import test from 'node:test'
import assert from 'node:assert/strict'
import { PDFDocument } from 'pdf-lib'
import { generateAppealPdf } from '../src/utils/pdfGenerator.js'

test('generateAppealPdf produces a valid 1-page A4 document', async () => {
  const driverProfile = {
    name: 'Violet Wanjiku',
    phone: '0712345678',
    platform: 'Bolt'
  }

  const caseData = {
    id: 104,
    platform: 'Bolt',
    narrative: '14 May around 4:30pm. Westlands to JKIA. The passenger said the fare was too high.',
    entities: [
      { label: 'DATE', text: '14 May 2026' },
      { label: 'TIME', text: '4:30 PM' },
      { label: 'ROUTE', text: 'Westlands to JKIA' },
      { label: 'FARE', text: 'KES 1,450' }
    ],
    evidence_held: ['SUSPENSION_NOTICE', 'TRIP_RECEIPT_SCREENSHOT', 'MPESA_RECEIPT']
  }

  const appealDossier = {
    headline: 'Formal Appeal: Unjust Account Restriction Regarding Trip #B-8831',
    statement_body: 'On 14 May 2026 at approximately 4:30 PM, I operated a trip from Westlands to JKIA. Upon arrival, the rider queried the toll surcharge. The transaction was verified via in-app receipt and M-Pesa transaction confirmation. Immediate account reinstatement is requested under NTSA Legal Notice 120 Regulation 15.',
    policy_rules: ['POL-NTSA-120-15', 'POL-KDPA-26']
  }

  const result = await generateAppealPdf({ driverProfile, caseData, appealDossier })

  assert.ok(result.pdfBytes, 'PDF bytes should be generated')
  assert.ok(result.pdfBytes.length > 0, 'PDF bytes should not be empty')
  assert.equal(result.pageCount, 1, 'Should strictly have 1 page')
  assert.match(result.filename, /^SautiYaDere_Appeal_SYD-APP-\d{4}-\d{4}\.pdf$/)

  // Parse generated bytes with PDFDocument to verify integrity
  const loadedDoc = await PDFDocument.load(result.pdfBytes)
  assert.equal(loadedDoc.getPageCount(), 1, 'Loaded document must contain exactly 1 page')

  const page = loadedDoc.getPage(0)
  const { width, height } = page.getSize()

  // Verify A4 dimensions (595.28 x 841.89 points)
  assert.ok(Math.abs(width - 595.28) < 0.1, `Width should match A4 (595.28), got ${width}`)
  assert.ok(Math.abs(height - 841.89) < 0.1, `Height should match A4 (841.89), got ${height}`)

  console.log(`Generated PDF size: ${result.pdfBytes.length} bytes (~${(result.pdfBytes.length / 1024).toFixed(2)} KB)`)
})

test('generateAppealPdf handles empty/sparse arguments gracefully', async () => {
  const result = await generateAppealPdf()
  assert.ok(result.pdfBytes)
  assert.equal(result.pageCount, 1)

  const loadedDoc = await PDFDocument.load(result.pdfBytes)
  assert.equal(loadedDoc.getPageCount(), 1)
})
